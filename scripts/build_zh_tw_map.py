#!/usr/bin/env python3
"""Generate static/zh-tw-map.js, the Simplified -> Traditional table for the UI.

Only characters and phrases that occur in the interface sources (static/ and
app/) are kept, so the table stays small. Data comes from OpenCC's
STCharacters/STPhrases dictionaries (Apache-2.0). Needs the dev-only package
``opencc-python-reimplemented``; the generated file is committed.

    python scripts/build_zh_tw_map.py
"""
from __future__ import annotations

import json
import os
import re
from pathlib import Path

import opencc

ROOT = Path(__file__).resolve().parents[1]
# i18n-extra.js holds English/Japanese values; its Chinese keys already occur in the other sources.
# The glossary's text reaches the page through structured_report, so it is converted too.
SOURCES = [p for p in ROOT.glob('static/*.js') if p.name != 'i18n-extra.js'] + [*ROOT.glob('static/*.html'), *ROOT.glob('app/*.py'),
                                                                              ROOT / 'docs/rules/glossary.md']
OUT = ROOT / 'static/zh-tw-map.js'
CJK = re.compile('[\u3400-\u9fff]')
# Domain overrides. None keeps the character: 干 is the heavenly stem (年干、宫干), 丑 the earthly
# branch, 斗 belongs to 北斗/斗数, 台 to the star 台辅, 咸 to 咸池, 凶 to 吉凶, 占 to 占卜.
# 冲 is the branch clash (六沖) and 钟 a clock (鐘), not 衝/鍾.
OVERRIDES = {'干': None, '丑': None, '斗': None, '台': None, '咸': None, '凶': None, '占': None,
             '冲': '沖', '钟': '鐘'}
KEEP = {c for c, t in OVERRIDES.items() if t is None}
# OpenCC phrases that misfire here: 合中 is 三合 followed by 中位 (三合中位), not 閤中.
SKIP_PHRASES = {'合中', '换发'}
# Calendar words OpenCC has no phrase for, where 历 is 曆 (a calendar), not 歷 (history); and 服务器, which Taiwan
# calls 伺服器.
EXTRA_PHRASES = {'历日': '曆日', '合历': '合曆', '服务器': '伺服器'}


def main() -> None:
    corpus = ''.join(p.read_text(encoding='utf-8') for p in sorted(SOURCES) if p != OUT)
    convert = opencc.OpenCC('s2tw').convert
    chars = {c: convert(c) for c in sorted(set(CJK.findall(corpus)))}
    chars.update({c: t for c, t in OVERRIDES.items() if t and c in chars})
    chars = {c: t for c, t in chars.items() if t != c and c not in KEEP}
    phrase_file = Path(os.path.dirname(opencc.__file__)) / 'dictionary' / 'STPhrases.txt'
    phrases, plain = {}, {}
    for line in phrase_file.read_text(encoding='utf-8').splitlines():
        key, _, values = line.partition('\t')
        if not key or key not in corpus or key in SKIP_PHRASES or any(c in KEEP for c in key):
            continue
        target = convert(key)
        if target != ''.join(chars.get(c, c) for c in key):
            phrases[key] = target
        else:
            plain[key] = target
    phrases.update({k: v for k, v in EXTRA_PHRASES.items() if k in corpus})
    # The page takes the longest phrase it finds (up to four characters), so a phrase that converts character by
    # character is still kept when a shorter kept phrase sits inside it: 电子表格 stays 電子表格, not 電子錶 + 格.
    phrases.update({k: v for k, v in plain.items() if len(k) <= 4 and any(short in k for short in phrases if len(short) < len(k))})
    body = ("'use strict';\n// Generated by scripts/build_zh_tw_map.py from OpenCC data (Apache-2.0). Do not edit.\n"
            f"const ZH_TW_CHARS = {json.dumps(chars, ensure_ascii=False, sort_keys=True)};\n"
            f"const ZH_TW_PHRASES = {json.dumps(phrases, ensure_ascii=False, sort_keys=True)};\n")
    OUT.write_text(body, encoding='utf-8')
    print(f'{OUT.relative_to(ROOT)}: {len(chars)} characters, {len(phrases)} phrases')


if __name__ == '__main__':
    main()
