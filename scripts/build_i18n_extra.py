#!/usr/bin/env python3
"""Generate static/i18n-extra.js from scripts/i18n_extra.json.

The JSON maps each Simplified Chinese source string (interface labels in
static/ and result text from app/) to [English, 日本語]. static/i18n.js uses it
for the English and Japanese interface. Run after adding Chinese text:

    python scripts/build_i18n_extra.py           # regenerate
    python scripts/build_i18n_extra.py --missing # list source strings without a translation
"""
from __future__ import annotations

import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / 'scripts/i18n_extra.json'
OUT = ROOT / 'static/i18n-extra.js'
CJK = re.compile('[㐀-鿿]')
UI_ROW = re.compile(r"\['((?:[^'\\]|\\.)*)', '")


def load() -> dict[str, list[str]]:
    data = json.loads(DATA.read_text(encoding='utf-8'))
    for key, value in data.items():
        if not CJK.search(key) or not (isinstance(value, list) and len(value) == 2 and all(isinstance(v, str) and v.strip() for v in value)):
            raise SystemExit(f'bad entry: {key!r}')
    return data


def source_strings() -> set[str]:
    """Plain string literals with Chinese text: static scripts, the page, and the engines."""
    found: set[str] = set()
    for path in [*ROOT.glob('static/*.js'), *ROOT.glob('app/*.py')]:
        if path.name in ('i18n.js', 'i18n-extra.js', 'zh-tw-map.js'):
            continue
        text = path.read_text(encoding='utf-8')
        quotes = [r"'((?:[^'\\\n]|\\.)*)'"] + ([r'"((?:[^"\\\n]|\\.)*)"'] if path.suffix == '.py' else [])
        for pattern in quotes:
            for m in re.finditer(pattern, text):
                value = m.group(1)
                if CJK.search(value) and '{' not in value and '\\' not in value:
                    found.add(value)
    found |= template_fragments()
    html = (ROOT / 'static/index.html').read_text(encoding='utf-8')
    found |= {m.strip() for m in re.findall(r'>([^<>{}\n]*[㐀-鿿][^<>{}\n]*)<', html)}
    found |= set(re.findall(r'(?:placeholder|title|aria-label)="([^"]*[㐀-鿿][^"]*)"', html))
    return found


def template_fragments() -> set[str]:
    """Literal pieces (two or more Chinese characters) of Python f-strings and JS template literals."""
    found: set[str] = set()
    for path in [*ROOT.glob('static/*.js'), *ROOT.glob('app/*.py')]:
        if path.name in ('i18n.js', 'i18n-extra.js', 'zh-tw-map.js'):
            continue
        text = path.read_text(encoding='utf-8')
        if path.suffix == '.py':
            bodies = [m.group(2) for m in re.finditer(r"""f(['"])((?:(?!\1).)*)\1""", text)]
            holes = r'\{[^{}]*\}'
        else:
            bodies = re.findall(r'`([^`]*)`', text)
            holes = r'\$\{[^{}]*\}'
        for body in bodies:
            found |= {part for part in re.split(holes, body) if len(CJK.findall(part)) >= 2}
    return found


def ui_text_keys() -> set[str]:
    source = (ROOT / 'static/i18n.js').read_text(encoding='utf-8')
    return set(UI_ROW.findall(source[source.index('const UI_TEXT = ['):source.index('];\n\nlet uiLang')]))


def missing() -> list[str]:
    known = set(load()) | ui_text_keys()
    return sorted(s for s in source_strings() if s not in known and s.strip() not in known)


def render(data: dict[str, list[str]]) -> str:
    body = json.dumps(dict(sorted(data.items())), ensure_ascii=False, indent=0)
    return ("'use strict';\n// Generated by scripts/build_i18n_extra.py from scripts/i18n_extra.json; do not edit.\n"
            "// Simplified Chinese source text -> [English, 日本語].\n"
            f'const UI_EXTRA = {body};\n')


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument('--missing', action='store_true')
    args = parser.parse_args()
    if args.missing:
        print('\n'.join(missing()))
        return
    data = load()
    OUT.write_text(render(data), encoding='utf-8')
    print(f'{OUT.relative_to(ROOT)}: {len(data)} entries')


if __name__ == '__main__':
    main()
